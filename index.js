/**
 * TypeScript wrapper around the WebAssembly build of IJG libjpeg 10 + transupp.
 *
 * The module exposes the same lossless transforms the `jpegtran` command line offers, applied in
 * memory instead of through files and subprocesses:
 *
 *   jpegtran -rotate 90 -perfect -copy all -crop 200x200+100+50 -outfile out.jpg in.jpg
 *
 * Nothing is dequantized or requantized, so the transforms are lossless.
 *
 * This file is written in "native" TypeScript: Node runs it directly by stripping the types, there
 * is no build step. Only erasable syntax is used (no enums, no namespaces, no parameter properties),
 * which `erasableSyntaxOnly` in tsconfig.json enforces.
 */
// The Emscripten module is generated by build.sh and ships without type declarations.
// @ts-ignore - no declarations for the generated module
import createJpegTran from "./dist/jpegtran.mjs";
/** Transform numbers, mirrored from the C enum in src/jpegtran_wrapper.c. */
export const TRANSFORM = {
    /** No rotation or flip. Useful for a crop on its own. */
    none: 0,
    /** 90 degrees clockwise. */
    rotate90: 1,
    rotate180: 2,
    /** 270 degrees clockwise, i.e. 90 degrees counter-clockwise. */
    rotate270: 3,
    flipHorizontal: 4,
    flipVertical: 5,
    transpose: 6,
    transverse: 7,
};
/** Marker copy modes, mirrored from the C enum. */
export const COPY = {
    none: 0,
    comments: 1,
    /** Keep Exif and every other APPn marker. */
    all: 2,
};
/** Return codes, mirrored from the C enum. */
export const STATUS = {
    ok: 0,
    badArgument: 1,
    notJpeg: 2,
    notPerfect: 3,
    library: 4,
    badCrop: 5,
};
/** Thrown whenever a transform fails. */
export class TransformError extends Error {
    /** One of {@link STATUS}. */
    status;
    /** The IJG message code (`JERR_*`). */
    msgCode;
    constructor(message, status, msgCode) {
        super(message);
        this.name = "TransformError";
        this.status = status;
        this.msgCode = msgCode;
    }
}
/** Accepts a Uint8Array or an ArrayBuffer and always returns a Uint8Array view. */
function asUint8Array(input) {
    if (input instanceof Uint8Array) {
        return input;
    }
    if (input instanceof ArrayBuffer) {
        return new Uint8Array(input);
    }
    throw new TypeError("input must be a Uint8Array or ArrayBuffer");
}
/** Maps the `-rotate` degrees of the command line to a transform number. */
function transformForDegrees(degrees) {
    switch (degrees) {
        case 90:
            return TRANSFORM.rotate90;
        case 180:
            return TRANSFORM.rotate180;
        case 270:
            return TRANSFORM.rotate270;
        default:
            throw new RangeError(`unsupported rotation: ${degrees} (expected 90, 180 or 270)`);
    }
}
/** Formats an offset the way jpegtran does: -10 stays "-10", 10 becomes "+10". */
function cropOffset(value) {
    return value < 0 ? `${value}` : `+${value}`;
}
/** Turns a crop region into jpegtran's `-crop` syntax. */
function cropSpecOf(crop) {
    if (typeof crop === "string") {
        return crop;
    }
    if (crop === null || typeof crop !== "object") {
        throw new TypeError("crop must be a string (jpegtran syntax) or an object");
    }
    if (!Number.isInteger(crop.width) || !Number.isInteger(crop.height)) {
        throw new TypeError("crop requires integer width and height");
    }
    const x = crop.x ?? 0;
    const y = crop.y ?? 0;
    if (!Number.isInteger(x) || !Number.isInteger(y)) {
        throw new TypeError("crop x and y must be integers when given");
    }
    return `${crop.width}x${crop.height}${cropOffset(x)}${cropOffset(y)}`;
}
/** Wraps the Emscripten module in a small, promise-free API. */
class JpegTransformer {
    #module;
    constructor(module) {
        this.#module = module;
    }
    /** The IJG libjpeg version string this module was built from. */
    version() {
        return this.#module.UTF8ToString(this.#module._mv_version());
    }
    /** Writes a buffer into the wasm heap and returns its pointer. */
    #writeBuffer(bytes) {
        const pointer = this.#module._malloc(bytes.length);
        this.#module.HEAPU8.set(bytes, pointer);
        return pointer;
    }
    /** Writes a NUL terminated string into the wasm heap and returns its pointer. */
    #writeCString(text) {
        const bytes = new TextEncoder().encode(text);
        const pointer = this.#module._malloc(bytes.length + 1);
        this.#module.HEAPU8.set(bytes, pointer);
        this.#module.HEAPU8[pointer + bytes.length] = 0;
        return pointer;
    }
    /** Reads the message of the last failing native call and throws it. */
    #fail(status) {
        const message = this.#module.UTF8ToString(this.#module._mv_last_message()) || "(no message)";
        throw new TransformError(message, status, this.#module._mv_last_msg_code());
    }
    /**
     * Reports whether the given transform is MCU aligned ("perfect") for this image, i.e. whether
     * jpegtran's `-perfect` would accept it without trimming edge blocks.
     *
     * Like jpegtran, this looks at the whole image: a crop region does not change the answer.
     */
    perfectPossible(input, transform) {
        const bytes = asUint8Array(input);
        const inPtr = this.#writeBuffer(bytes);
        const possiblePtr = this.#module._malloc(4);
        try {
            const status = this.#module._mv_jpeg_perfect_possible(inPtr, bytes.length, transform, possiblePtr);
            if (status !== STATUS.ok) {
                this.#fail(status);
            }
            return this.#module.HEAPU32[possiblePtr >>> 2] === 1;
        }
        finally {
            this.#module._free(possiblePtr);
            this.#module._free(inPtr);
        }
    }
    /**
     * Transforms and/or crops a JPEG in memory.
     *
     * @returns the result and the dimensions it ended up with
     */
    transformDetailed(input, options = {}) {
        const { transform = TRANSFORM.none, copy = COPY.all, perfect = false, crop = null } = options;
        const bytes = asUint8Array(input);
        const cropSpec = crop === null ? null : cropSpecOf(crop);
        const inPtr = this.#writeBuffer(bytes);
        const cropPtr = cropSpec === null ? null : this.#writeCString(cropSpec);
        const outPtrPtr = this.#module._malloc(4);
        const outLengthPtr = this.#module._malloc(4);
        const widthPtr = this.#module._malloc(4);
        const heightPtr = this.#module._malloc(4);
        const perfectPtr = this.#module._malloc(4);
        try {
            const status = this.#module._mv_jpeg_transform_full(inPtr, bytes.length, outPtrPtr, outLengthPtr, transform, copy, perfect ? 1 : 0, cropPtr ?? 0, perfectPtr, widthPtr, heightPtr);
            if (status !== STATUS.ok) {
                this.#fail(status);
            }
            // HEAPU8 may have been reallocated while the call grew the memory, so read it fresh.
            const outPtr = this.#module.HEAPU32[outPtrPtr >>> 2];
            const outLength = this.#module.HEAPU32[outLengthPtr >>> 2];
            const data = this.#module.HEAPU8.slice(outPtr, outPtr + outLength);
            this.#module._mv_free(outPtr);
            return {
                data,
                width: this.#module.HEAPU32[widthPtr >>> 2],
                height: this.#module.HEAPU32[heightPtr >>> 2],
            };
        }
        finally {
            this.#module._free(perfectPtr);
            this.#module._free(heightPtr);
            this.#module._free(widthPtr);
            this.#module._free(outLengthPtr);
            this.#module._free(outPtrPtr);
            if (cropPtr !== null) {
                this.#module._free(cropPtr);
            }
            this.#module._free(inPtr);
        }
    }
    /** Transforms a JPEG in memory and returns only the transformed bytes. */
    transform(input, options) {
        return this.transformDetailed(input, options).data;
    }
    /**
     * Crops a JPEG losslessly, without rotating it.
     *
     * The crop is applied to a copy of the DCT coefficients, so it costs no quality. Note that, like
     * jpegtran, the upper left corner is silently moved to an iMCU boundary and the region is grown to
     * cover what was asked for; use the `f` suffix in the spec (or pass a string) to keep the exact
     * dimensions instead.
     *
     * A transform may be given in `options` and is applied before the crop; the crop then refers to
     * the transformed image.
     */
    crop(input, rect, options = {}) {
        return this.transformDetailed(input, { ...options, crop: rect });
    }
    /**
     * Rotates a JPEG by 90, 180 or 270 degrees clockwise, mirroring
     * `jpegtran -rotate <degrees> -copy all`. The returned `perfect` flag tells whether the transform
     * was MCU aligned; the rotation is performed either way, which is what jpegtran does when
     * `-perfect` is omitted.
     */
    rotate(input, degrees, options = {}) {
        const transform = transformForDegrees(degrees);
        const perfectPossible = this.perfectPossible(input, transform);
        const { data, width, height } = this.transformDetailed(input, { ...options, transform });
        return { data, width, height, perfect: perfectPossible };
    }
}
/** Loads the WebAssembly module and returns the transformer. */
export async function createRotator() {
    const module = (await createJpegTran());
    return new JpegTransformer(module);
}
